import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import fontkit from '@pdf-lib/fontkit';
import { PDFDocument, rgb, type PDFPage, type PDFFont } from 'pdf-lib';
import type { RetroAction, RetroSessionView } from './types.js';

const fontPath = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../assets/NotoSans.ttf');
const PAGE_WIDTH = 595; const PAGE_HEIGHT = 842; const MARGIN = 48; const TEXT_WIDTH = PAGE_WIDTH - 2 * MARGIN;

export async function retrospectivePdf(session: RetroSessionView, actions: RetroAction[]): Promise<Uint8Array> {
  const pdf = await PDFDocument.create();
  pdf.registerFontkit(fontkit);
  const bytes = readFileSync(fontPath);
  const face = fontkit.create(bytes);
  const font = await pdf.embedFont(bytes, { subset: true });
  pdf.setTitle(`${session.title} — retrospective report`);
  pdf.setAuthor('UniteDesk');
  pdf.setSubject('Team retrospective and action items');
  let page: PDFPage = pdf.addPage([PAGE_WIDTH, PAGE_HEIGHT]); let y = PAGE_HEIGHT - MARGIN;
  const ink = rgb(.11, .13, .15); const muted = rgb(.42, .45, .48); const accent = rgb(.19, .34, .43);
  const safe = (value: string) => [...value].map((char) => face.hasGlyphForCodePoint(char.codePointAt(0)!) ? char : '□').join('');
  function nextPage() { page = pdf.addPage([PAGE_WIDTH, PAGE_HEIGHT]); y = PAGE_HEIGHT - MARGIN; }
  function ensure(height: number) { if (y - height < MARGIN) nextPage(); }
  function line(value: string, size = 10, color = ink, gap = 7) {
    const text = safe(value);
    const words = text.split(/\s+/).filter(Boolean);
    if (!words.length) { y -= size + gap; return; }
    let current = '';
    const draw = (part: string) => { ensure(size + 5); page.drawText(part, { x: MARGIN, y: y - size, size, font, color }); y -= size + gap; };
    for (const word of words) {
      const candidate = current ? `${current} ${word}` : word;
      if (font.widthOfTextAtSize(candidate, size) > TEXT_WIDTH && current) { draw(current); current = word; }
      else current = candidate;
      while (font.widthOfTextAtSize(current, size) > TEXT_WIDTH && current.length > 1) {
        let cut = current.length - 1;
        while (cut > 1 && font.widthOfTextAtSize(current.slice(0, cut), size) > TEXT_WIDTH) cut--;
        draw(current.slice(0, cut)); current = current.slice(cut);
      }
    }
    if (current) draw(current);
  }
  function section(title: string) { ensure(43); y -= 14; page.drawLine({ start: { x: MARGIN, y }, end: { x: PAGE_WIDTH - MARGIN, y }, thickness: .6, color: rgb(.78, .8, .81) }); y -= 12; line(title, 13, accent, 6); }
  function label(value: string) { line(value, 9, muted, 4); }

  line('UNITEDESK  /  RETROSPECTIVE REPORT', 9, accent, 16);
  line(session.title, 22, ink, 12);
  label(`Scheduled: ${new Date(session.scheduledAt).toLocaleString('en-GB', { dateStyle: 'medium', timeStyle: 'short' })}`);
  label(`Participants: ${session.members.map((member) => member.name).join(', ')}`);
  label(`${session.cards.length} cards  ·  ${session.groups.length} discussion topics  ·  ${actions.length} action items`);
  section('Discussion priorities');
  const groups = [...session.groups].sort((a, b) => b.votes - a.votes || a.title.localeCompare(b.title));
  for (const [index, group] of groups.entries()) {
    ensure(75); y -= 6;
    line(`${index + 1}. ${group.title}  ·  ${group.votes} vote${group.votes === 1 ? '' : 's'}`, 12, ink, 6);
    for (const cardId of group.cardIds) {
      const card = session.cards.find((item) => item.id === cardId); if (!card) continue;
      const column = session.columns.find((item) => item.id === card.columnId)?.name ?? 'Card';
      line(`    [${column}] ${card.text}`, 10, muted, 5);
    }
    if (group.notes) line(`    DISCUSSION: ${group.notes}`, 10, ink, 5);
    const groupActions = actions.filter((action) => action.groupId === group.id);
    for (const action of groupActions) line(`    ACTION: ${action.text} — ${action.assigneeName || 'Unassigned'}${action.dueDate ? `, due ${action.dueDate}` : ''}${action.completedAt ? ' (completed)' : ''}`, 9, accent, 5);
  }
  section('Action items to follow up');
  const open = actions.filter((action) => !action.completedAt);
  if (!open.length) line('No open action items.', 10, muted);
  for (const action of open) line(`• ${action.text} — ${action.assigneeName || 'Unassigned'}${action.dueDate ? `, due ${action.dueDate}` : ''}`, 10, ink, 7);
  y -= 15; label('Generated by UniteDesk. Source cards and completed actions remain in the retrospective record.');
  return pdf.save();
}
